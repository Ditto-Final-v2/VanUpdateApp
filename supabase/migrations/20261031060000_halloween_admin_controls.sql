-- Existing quest IDs and completion records stay intact; new tasks get unique IDs.
alter table public.halloween_quests alter column id add generated by default as identity;
select setval(pg_get_serial_sequence('public.halloween_quests','id'),coalesce((select max(id) from public.halloween_quests),0)+1,false);
grant insert,update on public.halloween_quests to service_role;
grant usage,select on sequence public.halloween_quests_id_seq to service_role;

create function public.halloween_adjust_tonic(p_delta integer)
returns integer language plpgsql security definer set search_path=public as $$
declare total integer;
begin
 if p_delta is null or p_delta=0 or abs(p_delta::bigint)>1000000 then
  raise exception 'Enter a nonzero adjustment between -1,000,000 and 1,000,000.';
 end if;
 update public.halloween_event set nuggets=nuggets+p_delta where id=1 and nuggets+p_delta>=0 returning nuggets into total;
 if not found then raise exception 'The community total cannot be negative.'; end if;
 return total;
end; $$;
revoke all on function public.halloween_adjust_tonic(integer) from public,anon,authenticated;
grant execute on function public.halloween_adjust_tonic(integer) to service_role;
